// Integration runner: mounted into an isolated Compose project, never real data.
import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {Updater} from '../server/updater/service.js';
import {fixture} from './fixtures.js';
import {appHTTP} from '../server/updater/app-http.js';
const u=new Updater({attempts:3});
const self=await u.docker.inspect(process.env.HOSTNAME);
assert.equal(self.Config.Labels['com.docker.compose.project'],'salmon-update-test');
assert.equal(self.Mounts.find(m=>m.Destination==='/data').Name,'salmon-update-test_salmon-data');
await u.init();let app=await u.discover();
const address=app.NetworkSettings.Networks['salmon-update-test_default'].IPAddress;
const get=async route=>(await appHTTP(address,route)).body;
const before=await get('/api/status');const f=fixture();
const imported=await appHTTP(address,'/api/import',{csrf:before.csrf,body:{documents:[f.summary,f.record]}});assert.equal(imported.status,200);
await writeFile('/data/update-fixture-secret.txt','local-only-fixture',{mode:0o600});
const image=await u.docker.image('salmon-review:local');
const manifest={version:'0.3.6',image:'salmon-review:local',imageIds:[image.Id],commit:image.Config.Labels['org.opencontainers.image.revision']};
u.manifest=async()=>manifest;u.download=async()=>{};u.docker.load=async()=>{};
u.info={available:true,latest:'0.3.6'};await u.install('0.3.6');await u.completion;
assert.equal(u.info.phase,'success',JSON.stringify(u.info));
assert.equal(await readFile('/data/update-fixture-secret.txt','utf8'),'local-only-fixture');
app=await u.discover();assert.equal((await u.appCall(app,'validate')).records,1);
await u.docker.stop(app.Id);await u.docker.start(app.Id);
await new Promise(resolve=>setTimeout(resolve,2000));
app=await u.discover();assert.equal((await u.appCall(app,'validate')).records,1);
const nextAddress=app.NetworkSettings.Networks['salmon-update-test_default'].IPAddress;
const status=(await appHTTP(nextAddress,'/api/status')).body;
const settings=await appHTTP(nextAddress,'/api/settings',{csrf:status.csrf,body:{autoMinutes:0}});
assert.equal(settings.status,200,'updated app remains writable after container restart');
console.log('PASS: real container replacement, record/secret preservation, restart after activation');
// Simulate a power loss after rename and after a candidate wrote damaged data.
const old=await u.discover(),id='recoveryfixture',name=old.Name.slice(1),backup='/updates/backups/'+id;
await mkdir('/updates/backups',{recursive:true});await u.appCall(old,'prepare');await u.docker.stop(old.Id);await u.backup('/data',backup);
await u.docker.rename(old.Id,name+'-rollback-'+id);await writeFile('/data/update-fixture-secret.txt','simulated-damage');
await u.recover({id,oldId:old.Id,name,backup,backupComplete:true,version:'0.3.6'});
assert.equal(await readFile('/data/update-fixture-secret.txt','utf8'),'local-only-fixture');
assert.equal((await u.appCall(await u.discover(),'validate')).records,1);
console.log('PASS: interrupted replacement recovers original container, records and local secret');
